(* Conformance binding for the symdiff model vectors (.grounds/conformance/).
   Reads the grounds-vectors/1 files generated by ImandraX for the model of
   Sym (gravity/lib/symbolic.ml), binds every vector to the real OCaml
   function, compares structurally, and reports agree/disagree counts.
   One test per vector, named by its id.

   Usage: symdiff_conformance.exe [DIR]
     DIR defaults to .grounds/conformance under the dune project root found by
     walking up from the current directory.

   NOTE: Sym is accessed qualified (module S) because Sym overloads the
   addition and multiplication operators for terms, which would shadow
   integer/float arithmetic in this file. *)

module S = Gravlib.Symbolic.Sym

(* ---- Minimal JSON parser for the vectors subset ---- *)

type json =
  | JNull
  | JBool of bool
  | JInt of int
  | JReal of float          (* parsed from a {"$real": "n/d"} object *)
  | JString of string
  | JObj of (string * json) list
  | JArr of json list

exception Json_error of string

let skip_ws s i =
  let n = String.length s in
  let rec skip k =
    if k < n && (String.get s k = ' ' || String.get s k = '\t'
                 || String.get s k = '\n' || String.get s k = '\r')
    then skip (Stdlib.(k + 1)) else k
  in
  skip i

let parse_string s i =
  (* s.[i] = '"' *)
  let n = String.length s in
  let b = Buffer.create 16 in
  let rec go i =
    if i >= n then raise (Json_error "unterminated string")
    else match String.get s i with
      | '"' -> i + 1
      | '\\' ->
        (match String.get s (i+1) with
         | 'n' -> Buffer.add_char b '\n'; go (i + 2)
         | 't' -> Buffer.add_char b '\t'; go (i + 2)
         | 'r' -> Buffer.add_char b '\r'; go (i + 2)
         | '"' -> Buffer.add_char b '"'; go (i + 2)
         | '\\' -> Buffer.add_char b '\\'; go (i + 2)
         | c -> Buffer.add_char b c; go (i + 2))
      | c -> Buffer.add_char b c; go (i + 1)
  in
  let j = go (i + 1) in
  (Buffer.contents b, j)

let rec parse_value s i =
  let i = skip_ws s i in
  let n = String.length s in
  if i >= n then raise (Json_error "unexpected end")
  else match String.get s i with
    | '{' -> parse_object s i
    | '[' -> parse_array s i
    | '"' -> let v, j = parse_string s i in (JString v, j)
    | 't' -> (JBool true, i + 4)
    | 'f' -> (JBool false, i + 5)
    | 'n' -> (JNull, i + 4)
    | c when c = '-' || (c >= '0' && c <= '9') ->
      let j = ref i in
      while !j < n && (let c = String.get s !j in
        (c >= '0' && c <= '9') || c = '.' || c = 'e' || c = 'E'
        || c = '-' || c = '+') do Stdlib.(j := !j + 1) done;
      let tok = String.sub s i (!j - i) in
      (JReal (float_of_string tok), !j)
    | c -> raise (Json_error (Printf.sprintf "unexpected char %c" c))

and parse_array s i =
  (* s.[i] = '[' *)
  let n = String.length s in
  let rec go acc j =
    let j = skip_ws s j in
    if j < n && String.get s j = ']' then (JArr (List.rev acc), j + 1)
    else
      let v, k = parse_value s j in
      let k = skip_ws s k in
      if k < n && String.get s k = ',' then go (v :: acc) (k + 1)
      else if k < n && String.get s k = ']' then (JArr (List.rev (v :: acc)), k + 1)
      else raise (Json_error "bad array")
  in
  go [] (i + 1)

and parse_object s i =
  (* s.[i] = '{' *)
  let n = String.length s in
  let rec go acc j =
    let j = skip_ws s j in
    if j < n && String.get s j = '}' then (JObj (List.rev acc), j + 1)
    else
      let k = skip_ws s j in
      let key, k = parse_string s k in
      let k = skip_ws s k in
      if k >= n || String.get s k <> ':' then raise (Json_error "expected ':'")
      else
        let v, k = parse_value s (k + 1) in
        let k = skip_ws s k in
        if k < n && String.get s k = ',' then go ((key, v) :: acc) (k + 1)
        else if k < n && String.get s k = '}' then (JObj (List.rev ((key, v) :: acc)), k + 1)
        else raise (Json_error "bad object")
  in
  go [] (i + 1)

let parse_file path =
  let ic = open_in_bin path in
  let n = in_channel_length ic in
  let s = really_input_string ic n in
  close_in ic;
  let v, _ = parse_value s 0 in
  v

let obj_field name = function
  | JObj fs -> (try List.assoc name fs with Not_found -> raise (Json_error ("missing field " ^ name)))
  | _ -> raise (Json_error "not an object")

let obj_field_opt name = function
  | JObj fs -> (try Some (List.assoc name fs) with Not_found -> None)
  | _ -> None

let as_string = function JString s -> s | _ -> raise (Json_error "not a string")
let as_int = function JInt i -> i | JReal f when Float.is_integer f -> int_of_float f
  | _ -> raise (Json_error "not an int")

let decode_real = function
  | JObj [("$real", JString r)] ->
    (match String.split_on_char '/' r with
     | [num; den] -> float_of_string num /. float_of_string den
     | _ -> float_of_string r)
  | JReal f -> f
  | _ -> raise (Json_error "bad real")

let rec decode_term j =
  let c = as_string (obj_field "$c" j) in
  let args = match obj_field "args" j with JArr a -> a | _ -> raise (Json_error "bad args") in
  match c, args with
  | "Add", [a; b] -> S.Add (decode_term a, decode_term b)
  | "Mul", [a; b] -> S.Mul (decode_term a, decode_term b)
  | "Pow", [n; a] -> S.Pow (decode_real n, decode_term a)
  | "Var", [i] -> S.Var (as_int i, "v")
  | "Const", [r] -> S.Const (decode_real r)
  | _ -> raise (Json_error ("bad term constructor " ^ c))

let rec pp_term t =
  match t with
  | S.Add (a, b) -> Printf.sprintf "Add(%s, %s)" (pp_term a) (pp_term b)
  | S.Mul (a, b) -> Printf.sprintf "Mul(%s, %s)" (pp_term a) (pp_term b)
  | S.Pow (n, a) -> Printf.sprintf "Pow(%g, %s)" n (pp_term a)
  | S.Var (i, s) -> Printf.sprintf "Var(%d,%s)" i s
  | S.Const c -> Printf.sprintf "Const(%g)" c

let param_names_of_fn fn =
  match fn with
  | "add" | "mul" -> ["a"; "b"]
  | "pow_norm" -> ["n"; "a"]
  | "simplify" -> ["x"]
  | "deriv" -> ["x"; "y"]
  | _ -> raise (Json_error ("unknown function " ^ fn))

let eval_vector fn params v =
  (* decode the input per function parameter order, then run the real code *)
  let input = obj_field "input" v in
  let dec t = decode_term t in
  match fn with
  | "add" -> S.add (dec (obj_field (List.nth params 0) input)) (dec (obj_field (List.nth params 1) input))
  | "mul" -> S.mul (dec (obj_field (List.nth params 0) input)) (dec (obj_field (List.nth params 1) input))
  | "pow_norm" ->
    let n = decode_real (obj_field "n" input) in
    let a = dec (obj_field "a" input) in
    S.pow_norm n a
  | "simplify" -> S.simplify (dec (obj_field "x" input))
  | "deriv" -> S.deriv (dec (obj_field "x" input)) (dec (obj_field "y" input))
  | _ -> raise (Json_error ("unknown function " ^ fn))

let rec find_gravity_root dir =
  if Sys.file_exists (Filename.concat dir "dune-project") then dir
  else
    let parent = Filename.dirname dir in
    if parent = dir then raise (Json_error "could not find dune-project root")
    else find_gravity_root parent

let () =
  let cwd = Sys.getcwd () in
  let root =
    try
      if Array.length Sys.argv > 1 then Sys.argv.(1)
      else Filename.concat (find_gravity_root cwd) ".grounds/conformance"
    with Json_error e -> prerr_endline ("ERROR: " ^ e); exit 2
  in
  let files =
    Sys.readdir root |> Array.to_list
    |> List.filter (fun f -> Filename.check_suffix f ".vectors.json")
    |> List.sort compare
    |> List.map (Filename.concat root)
  in
  let total = ref 0 and agreed = ref 0 in
  List.iter (fun f ->
    let doc = parse_file f in
    let fn = as_string (obj_field "function" doc) in
    let params = param_names_of_fn fn in
    let vectors = match obj_field "vectors" doc with
      | JArr vs -> vs
      | _ -> raise (Json_error "no vectors") in
    List.iter (fun v ->
      let id = as_string (obj_field "id" v) in
      let expected = decode_term (obj_field "expected" v) in
      let got = eval_vector fn params v in
      incr total;
      if got = expected then incr agreed
      else begin
        Printf.printf "MISMATCH %s: got %s expected %s\n%!"
          id (pp_term got) (pp_term expected)
      end
    ) vectors
  ) files;
  Printf.printf "conformance: %d/%d vectors agreed\n%!" !agreed !total;
  if !agreed <> !total then exit 1