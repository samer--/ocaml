(* Conformance binding for the utils-pairs model vectors (.grounds/conformance/).
   Reads the grounds-vectors/1 files generated by ImandraX for the model of
   Utils.pairs (gravity/lib/utils.ml), binds every vector to the real OCaml
   function, compares structurally, and reports agree/disagree counts.
   One test per vector, named by its id.

   Usage: pairs_conformance.exe [DIR]
     DIR defaults to .grounds/conformance under the dune project root. *)

module Y = Yojson.Safe

exception Json_error of string

let obj_field name = function
  | `Assoc fs -> (try List.assoc name fs with Not_found -> raise (Json_error ("missing field " ^ name)))
  | _ -> raise (Json_error "not an object")

let as_list = function `List a -> a | _ -> raise (Json_error "not a list")
let as_string = function `String s -> s | _ -> raise (Json_error "not a string")
let as_int = function `Int i -> i | `Float f when Float.is_integer f -> int_of_float f
  | _ -> raise (Json_error "not an int")

let rec decode_int_list = function
  | `List js -> List.map as_int js
  | _ -> raise (Json_error "not an int list")

let rec decode_tuple_list = function
  | `List js -> List.map (function
      | `Assoc [("$tuple", `List [`Int a; `Int b])] -> (a, b)
      | j -> raise (Json_error ("bad tuple: " ^ Y.to_string j))
    ) js
  | j -> raise (Json_error ("not a tuple list: " ^ Y.to_string j))

let pp_pair (a, b) = Printf.sprintf "(%d,%d)" a b
let pp_pairs ps = "[" ^ String.concat "; " (List.map pp_pair ps) ^ "]"

let rec find_gravity_root dir =
  if Sys.file_exists (Filename.concat dir "dune-project") then dir
  else
    let parent = Filename.dirname dir in
    if parent = dir then raise (Json_error "could not find dune-project root")
    else find_gravity_root parent

let () =
  let cwd = Sys.getcwd () in
  let root =
    try
      if Array.length Sys.argv > 1 then Sys.argv.(1)
      else Filename.concat (find_gravity_root cwd) ".grounds/conformance"
    with Json_error e -> prerr_endline ("ERROR: " ^ e); exit 2
  in
  let total = ref 0 and agreed = ref 0 in
  Array.to_list (Sys.readdir root)
  |> List.filter (fun f -> Filename.check_suffix f "utils-pairs.vectors.json")
  |> List.sort compare
  |> List.map (Filename.concat root)
  |> List.map Y.from_file
  |> List.iter (fun doc ->
    as_list (obj_field "vectors" doc)
    |> List.iter (fun v ->
      let id = as_string (obj_field "id" v) in
      let input = obj_field "input" v in
      let xs = decode_int_list (obj_field "xs" input) in
      let expected = decode_tuple_list (obj_field "expected" v) in
      let got = Gravlib.Utils.pairs xs in
      incr total;
      if got = expected then incr agreed
      else begin
        Printf.printf "MISMATCH %s: got %s expected %s\n%!"
          id (pp_pairs got) (pp_pairs expected)
      end
    )
  );
  Printf.printf "conformance: %d/%d vectors agreed\n%!" !agreed !total;
  if !agreed <> !total then exit 1
